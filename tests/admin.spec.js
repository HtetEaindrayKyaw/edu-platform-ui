import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.route('https://fonts.googleapis.com/**', route => route.abort())
})

test('create a question and published exam, complete it, and retain its result after reload', async ({ page }) => {
  await page.goto('/#/admin/question-bank')
  await page.getByRole('button', { name: 'Add question' }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('Question', { exact: true }).fill('Which value is the answer in this integration test?')
  await dialog.getByRole('combobox', { name: 'Subject', exact: true }).selectOption('Physics')
  await dialog.getByLabel('Topic', { exact: true }).fill('Integration topic')
  for (const [letter, value] of [['A','One'],['B','Two'],['C','Three'],['D','Four']]) await dialog.getByRole('textbox', { name: `Option ${letter}`, exact: true }).fill(value)
  await dialog.getByRole('radio', { name: 'Option B is correct' }).check()
  await dialog.getByRole('combobox', { name: 'Status', exact: true }).selectOption('Published')
  await dialog.getByRole('button', { name: 'Save question' }).click()
  await expect(page.getByRole('cell', { name: /Which value is the answer/ })).toBeVisible()
  await page.getByRole('button', { name: 'Exams', exact: true }).click()
  await page.getByRole('button', { name: 'Create exam', exact: false }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Exam title').fill('Integration physics exam')
  await dialog.getByRole('combobox', { name: 'Subject', exact: true }).selectOption('Physics')
  await dialog.getByRole('combobox', { name: 'Topic', exact: true }).selectOption('Integration topic')
  await dialog.getByLabel('Question count').fill('1')
  await dialog.getByRole('combobox', { name: 'Status', exact: true }).selectOption('Published')
  await dialog.getByRole('button', { name: 'Save exam' }).click()
  await expect(dialog).not.toBeVisible()
  await page.reload()
  const exam = page.locator('.admin-exam-card').filter({ has: page.getByRole('heading', { name: 'Integration physics exam' }) })
  await exam.getByRole('button', { name: 'Try exam' }).click()
  const examIntro = page.getByRole('dialog', { name: 'Exam instructions' })
  await expect(examIntro.getByRole('heading', { name: 'Integration physics exam' })).toBeVisible()
  await expect(examIntro.locator('.exam-intro-details')).toContainText('Questions')
  await expect(examIntro.locator('.exam-intro-details').getByText('1', { exact: true })).toBeVisible()
  await expect(examIntro.locator('.exam-intro-details')).toContainText('10 minutes')
  await examIntro.getByRole('button', { name: 'Begin exam' }).click()
  await page.getByRole('button', { name: 'B Two' }).click()
  await page.getByRole('button', { name: 'Finish practice' }).click()
  await expect(page.locator('.result>strong')).toHaveText('100%')
  await page.getByRole('button', { name: 'View practice history' }).click()
  await page.getByRole('button', { name: 'Admin panel', exact: true }).click()
  await page.getByRole('button', { name: 'Results', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'Integration physics exam' })).toContainText('100%')
  await page.reload()
  await expect(page.getByRole('row').filter({ hasText: 'Integration physics exam' })).toContainText('Passed')
})

