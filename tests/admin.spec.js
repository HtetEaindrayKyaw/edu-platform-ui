test('reject insufficient questions and protect published exams when archiving', async ({ page }) => {
  await page.goto('/#/admin/exams')
  await page.getByRole('button', { name: 'Create exam', exact: false }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Exam title').fill('Too many questions')
  await dialog.getByLabel('Question count').fill('20')
  await dialog.getByRole('combobox', { name: 'Status', exact: true }).selectOption('Published')
  await dialog.getByRole('button', { name: 'Save exam' }).click()
  await expect(dialog.getByRole('alert')).toContainText('Only 5 published questions match')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Question bank', exact: true }).click()
  await page.getByRole('textbox', { name: 'Search question bank' }).fill('derivative')
  const row = page.getByRole('row').filter({ hasText: 'What is the derivative' })
  await row.getByRole('button', { name: 'Archive', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('before archiving')
  await expect(row).toContainText('Published')
  await page.getByRole('button', { name: 'Exams', exact: true }).click()
  const math = page.locator('.admin-exam-card').filter({ hasText: 'Mathematics foundations' })
  await math.getByRole('button', { name: 'Unpublish', exact: false }).click()
  await page.getByRole('button', { name: 'Question bank', exact: true }).click()
  await page.getByRole('textbox', { name: 'Search question bank' }).fill('derivative')
  await row.getByRole('button', { name: 'Archive', exact: true }).click()
  await expect(row).toContainText('Archived')
  await row.getByRole('button', { name: 'Restore', exact: true }).click()
  await expect(row).toContainText('Draft')
})

test('student records and settings persist, and admin layouts fit mobile', async ({ page }) => {
  await page.goto('/#/admin/students')
  await page.getByRole('button', { name: 'Add student', exact: false }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('Full name').fill('Test Learner')
  await dialog.getByLabel('Email', { exact: true }).fill('learner@example.com')
  await dialog.getByRole('button', { name: 'Save record' }).click()
  await page.getByRole('textbox', { name: 'Search students' }).fill('learner@example.com')
  const row = page.getByRole('row').filter({ hasText: 'learner@example.com' })
  await row.getByRole('button', { name: 'Deactivate', exact: true }).click()
  await expect(row).toContainText('Inactive')
  await page.reload()
  await expect(row).toContainText('Inactive')
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByLabel('Workspace name').fill('Test Academy')
  await page.getByLabel('Passing score (%)').fill('75')
  await page.getByRole('button', { name: 'Save changes' }).click()
  await page.reload()
  await expect(page.getByLabel('Workspace name')).toHaveValue('Test Academy')
  await page.setViewportSize({ width: 390, height: 844 })
  for (const section of ['overview','question-bank','exams','students','results','settings']) {
    await page.goto(`/#/admin/${section}`)
    await expect(page.locator('h1')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
  await page.goto('/#/admin/question-bank')
  await page.getByRole('button', { name: 'Add question', exact: false }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
})

test('admin overview and question editor render without browser errors', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1060 })
  await page.goto('/#/admin/overview')
  await expect(page.getByRole('heading', { name: 'A clearer view of your classroom.' })).toBeVisible()
  await page.screenshot({ path: 'outputs/admin-overview-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Add question', exact: false }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.screenshot({ path: 'outputs/admin-question-editor.png', fullPage: true })
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'outputs/admin-overview-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Student portal', exact: false }).first().click()
  await expect(page.locator('h1')).toContainText('Let’s make progress')
  expect(errors).toEqual([])
})
